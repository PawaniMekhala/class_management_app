import '../../models/payment_model.dart';

class PaymentService {
  static final List<PaymentCharge> _charges = [];
  static final List<StudentPayment> _payments = [];
  static bool _demoChargesInitialized = false;

  // TO DO BACKEND:
  // GET /api/institutes/{instituteId}/students/{studentId}/charges
  Future<List<PaymentCharge>> getStudentCharges(
    int instituteId,
    int studentId,
  ) async {
    _initializeDemoCharges();
    return _charges
        .where(
          (charge) =>
              charge.instituteId == instituteId &&
              charge.studentId == studentId,
        )
        .toList();
  }

  // TO DO BACKEND:
  // GET /api/institutes/{instituteId}/charges/outstanding
  Future<List<PaymentCharge>> getOutstandingCharges(int instituteId) async {
    _initializeDemoCharges();

    await Future.delayed(const Duration(milliseconds: 300));

    return _charges
        .where(
          (charge) => charge.instituteId == instituteId && charge.balance > 0,
        )
        .toList();
  }

  // TO DO BACKEND:
  // GET /api/institutes/{instituteId}/payments
  Future<List<StudentPayment>> getPayments(int instituteId) async {
    return _payments
        .where((payment) => payment.instituteId == instituteId)
        .toList();
  }

  // Temporary demo helper.
  // Later charges must be generated by the backend
  // using enrollment and payment plan rules.
  Future<void> addDemoCharge(PaymentCharge charge) async {
    _initializeDemoCharges();

    if (_charges.any(
      (item) => item.id == charge.id && item.instituteId == charge.instituteId,
    )) {
      throw Exception('Charge already exists.');
    }

    _charges.add(charge);
  }

  // TO DO BACKEND:
  // POST /api/institutes/{instituteId}/payments
  //
  // Backend must save the payment and charge allocations
  // in a single database transaction.
  Future<StudentPayment> collectPayment({
    required int instituteId,
    required int studentId,
    required String method,
    required List<PaymentAllocation> allocations,
  }) async {
    _initializeDemoCharges();
    const allowedMethods = {'cash', 'card', 'bank_transfer', 'online'};

    if (!allowedMethods.contains(method)) {
      throw Exception('Invalid payment method.');
    }

    if (allocations.isEmpty) {
      throw Exception('Select at least one charge.');
    }

    final chargeIds = allocations.map((a) => a.chargeId).toSet();

    if (chargeIds.length != allocations.length) {
      throw Exception('Duplicate charge selected.');
    }

    final updates = <int, PaymentCharge>{};
    double total = 0;

    // Validate every allocation before changing any data.
    for (final allocation in allocations) {
      final index = _charges.indexWhere(
        (charge) =>
            charge.id == allocation.chargeId &&
            charge.instituteId == instituteId &&
            charge.studentId == studentId,
      );

      if (index == -1) {
        throw Exception('Charge not found.');
      }

      final charge = _charges[index];

      if (!allocation.amount.isFinite ||
          allocation.amount <= 0 ||
          allocation.amount > charge.balance + 0.001) {
        throw Exception('Invalid payment amount for ${charge.className}.');
      }

      updates[index] = charge.copyWith(
        paidAmount: charge.paidAmount + allocation.amount,
      );

      total += allocation.amount;
    }

    final nextId = _payments.isEmpty ? 1 : _payments.last.id + 1;

    final payment = StudentPayment(
      id: nextId,
      instituteId: instituteId,
      studentId: studentId,
      paidAt: DateTime.now(),
      method: method,
      amount: total,
      allocations: List.unmodifiable(allocations),
      receiptNumber: 'PAY-${nextId.toString().padLeft(6, '0')}',
    );

    // Demo update: all validation has succeeded.
    for (final entry in updates.entries) {
      _charges[entry.key] = entry.value;
    }

    _payments.add(payment);

    return payment;
  }

  void _initializeDemoCharges() {
    if (_demoChargesInitialized) return;

    _charges.addAll([
      PaymentCharge(
        id: 1,
        instituteId: 1,
        studentId: 9,
        enrollmentId: 0, // Demo only; replace with real enrollment ID.
        classId: 4,
        className: '2026 A/L Biology (Revision)',
        description: 'October 2026 · A/L monthly fee',
        dueDate: DateTime(2026, 10, 7),
        originalAmount: 3000,
        discountAmount: 300,
        paidAmount: 0,
        discountDescription: 'Sibling discount (10%)',
        tuteDescription: 'Biology — Unit 4',
      ),
      PaymentCharge(
        id: 2,
        instituteId: 1,
        studentId: 9,
        enrollmentId: 0, // Demo only.
        classId: 3,
        className: '2026 A/L Chemistry (Revision)',
        description: 'October 2026 · A/L monthly fee',
        dueDate: DateTime(2026, 10, 7),
        originalAmount: 3000,
        discountAmount: 0,
        paidAmount: 0,
        tuteDescription: 'Chemistry — Unit 04',
      ),
    ]);

    _demoChargesInitialized = true;
  }
}
